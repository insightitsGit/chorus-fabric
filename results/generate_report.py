chunk_count_per_log = {}

for logf in log_files:
    path = 'results/' + logf
    size = os.path.getsize(path)
    mode_chunks = {'direct': 0, 'isolation': 0, 'superposition': 0}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line: continue
            try: obj = json.loads(line)
            except: continue
            ev   = obj.get('event') or obj.get('ev')
            mode = obj.get('mode')
            seq  = obj.get('seq') or obj.get('seq_num')
            rtt  = obj.get('rtt_ms')
            if ev == 'chunk_ack' and mode in data and seq is not None and rtt is not None:
                if seq >= warmup:
                    data[mode].append({'seq': seq, 'rtt_ms': rtt,
                                       'verified': obj.get('verified', True),
                                       'status': obj.get('status', '')})
                    mode_chunks[mode] += 1
    chunk_count_per_log[logf] = {'size_kb': round(size/1024, 1), 'modes': mode_chunks}

stats = {}
for mode in ['direct', 'isolation', 'superposition']:
    chunks = data[mode]
    seqs   = sorted(chunks, key=lambda x: x['seq'])
    intervals = [seqs[i]['rtt_ms'] - seqs[i-1]['rtt_ms']
                 for i in range(1, len(seqs))
                 if 50 < (seqs[i]['rtt_ms'] - seqs[i-1]['rtt_ms']) < 2000]
    verified = sum(1 for c in chunks if c['verified'])
    srt = sorted(intervals)
    stats[mode] = {
        'total_chunks':    len(chunks),
        'verified':        verified,
        'verified_pct':    round(100*verified/len(chunks), 2) if chunks else 0,
        'min_ms':          round(min(intervals), 1) if intervals else 0,
        'avg_ms':          round(statistics.mean(intervals), 1) if intervals else 0,
        'p50_ms':          round(statistics.median(intervals), 1) if intervals else 0,
        'p95_ms':          round(srt[int(len(srt)*0.95)], 1) if srt else 0,
        'p99_ms':          round(srt[int(len(srt)*0.99)], 1) if srt else 0,
        'max_ms':          round(max(intervals), 1) if intervals else 0,
        'throughput_kbs':  round((len(chunks)*512) / (sum(intervals)/1000) / 1024, 2) if intervals else 0,
    }

total_verified = sum(s['verified'] for s in stats.values())
